// Obsidian Markdown generation + tiny zip writer + vault sync. DOM-free except dirIO (File System Access API).
import { exMap, fields, doneSets, doneWorkouts, history, bests, fmtSet, fmtTarget, fmtW, e1rm, num, skillCurrent, localDate,
  volumeOf, varName, critText, suggest, nextDayPain, autoUnlock } from './logic.js';
import { RISK, REGIONS, TENDON_GUIDE, LIMB_NOTE } from './program.js';

export const ROOT = 'Fitness';
const GEN = '<!-- Generated by Tiger Training OS. Edits here are overwritten on the next sync (a backup copy is kept in _data/backups/). -->';
const yaml = o => '---\n' + Object.entries(o).filter(([, v]) => v != null && v !== '' && !(Array.isArray(v) && !v.length))
  .map(([k, v]) => `${k}: ${Array.isArray(v) ? '[' + v.map(q).join(', ') + ']' : typeof v === 'string' ? q(v) : v}`).join('\n') + '\n---\n';
const q = s => typeof s === 'number' ? s : JSON.stringify(String(s));
const safe = s => s.replace(/[\\/:*?"<>|#^[\]]/g, '-');
const cell = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const mmss = s => s == null ? '' : `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;

export function workoutPath(db, w) {
  if (w.mdPath) return w.mdPath;
  const base = `${ROOT}/Workouts/${w.date} - ${safe(w.name)}`;
  const taken = new Set(db.workouts.filter(o => o.id !== w.id && o.mdPath).map(o => o.mdPath));
  for (let i = 1; ; i++) { const p = `${base}${i > 1 ? ` (${i})` : ''}.md`; if (!taken.has(p)) return p; }
}
const link = p => p ? `[[${p.replace(/\.md$/, '').split('/').pop()}]]` : '';

// Actual rest before each done set, from completion timestamps (gaps > 15 min ignored).
export function restTimes(w) {
  const all = w.entries.flatMap(e => doneSets(e).map(s => ({ s, e }))).filter(x => x.s.at).sort((a, b) => a.s.at.localeCompare(b.s.at));
  const out = new Map();
  all.forEach((x, i) => { if (i) { const d = Math.round((Date.parse(x.s.at) - Date.parse(all[i - 1].s.at)) / 1000); if (d > 0 && d < 900) out.set(x.s.id, d); } });
  return out;
}

const COLS = { w: 'Weight', r: 'Reps', t: 'Sec', d: 'Dist' };
export function workoutMd(db, w) {
  const X = exMap(db), rest = restTimes(w), e1 = {}, cap = db.settings.painCap ?? 3;
  for (const en of w.entries) { const ex = X[en.ex]; if (ex) for (const s of doneSets(en)) { const v = e1rm(ex, num(s.w), num(s.r)); if (v > (e1[ex.id] || 0)) e1[ex.id] = v; } }
  const done = w.entries.filter(e => X[e.ex] && doneSets(e).length);
  const tendon = done.filter(e => X[e.ex].cat === 'tendon'), skill = done.filter(e => e.variant || X[e.ex].tree);
  const pains = done.filter(e => num(e.pain) != null);
  const { sets, tonnage } = volumeOf(db, w);
  const dur = w.finishedAt && w.startedAt ? Math.round((Date.parse(w.finishedAt) - Date.parse(w.startedAt)) / 6e4) : null;
  const fm = {
    type: 'workout', id: w.id, date: w.date, workout: w.name, rotation: w.type, focus: w.title,
    started: w.startedAt, finished: w.finishedAt, duration_min: dur && dur > 0 && dur < 600 ? dur : null,
    bodyweight: w.bw ?? null, sets, volume_lb: tonnage, tendon_sets: tendon.reduce((a, e) => a + doneSets(e).length, 0),
    skill_sets: skill.reduce((a, e) => a + doneSets(e).length, 0), pain_max: pains.length ? Math.max(...pains.map(e => +e.pain)) : null,
    exercises: done.map(e => X[e.ex].name), pr_count: (w.prs || []).length,
    ...Object.fromEntries(Object.entries(e1).map(([k, v]) => [`e1rm_${k}`, v])),
    edited: w.editedAt, tags: ['fitness/workout'],
  };
  let s = yaml(fm) + `\n# ${w.name}${w.title ? ' — ' + w.title : ''} — ${w.date}\n\n`;
  for (const en of done) {
    const ex = X[en.ex];
    const meta = [en.variant && `Variation: **${varName(ex, en.variant)}**`, en.subFor && `sub for ${X[en.subFor]?.name || en.subFor}`,
      en.form && `Form: ${en.form === 'good' ? '✓ solid' : '✗ off'}`, num(en.pain) != null && `Pain: ${en.pain}/10`].filter(Boolean).join(' · ');
    s += `## ${ex.name}\n\nTarget: ${fmtTarget(ex, en.tgt)} · [[${safe(ex.name)}]]${meta ? '\n' + meta : ''}\n\n`;
    const f = Object.keys(COLS).filter(k => fields(ex).includes(k));
    s += `| Set | ${f.map(k => COLS[k] + (k === 'd' ? ` (${ex.dUnit || ''})` : '')).join(' | ')} | RPE | Rest |\n|---|${f.map(() => '---').join('|')}|---|---|\n`;
    doneSets(en).forEach((st, i) => {
      s += `| ${i + 1} | ${f.map(k => k === 'w' && ex.kind === 'load' ? fmtW(ex, st.w) : cell(st[k])).join(' | ')} | ${cell(st.rpe)} | ${mmss(rest.get(st.id))} |\n`;
    });
    if (en.notes) s += `\n> ${cell(en.notes)}\n`;
    s += '\n';
  }
  const skipped = w.entries.filter(e => X[e.ex] && !doneSets(e).length).map(e => X[e.ex].name);
  if (skipped.length) s += `Skipped: ${skipped.join(', ')}\n\n`;
  const line = e => `- [[${safe(X[e.ex].name)}]]${e.variant ? ` (${varName(X[e.ex], e.variant)})` : ''}: ${doneSets(e).map(x => fmtSet(X[e.ex], x)).join(' · ')}${num(e.pain) != null ? ` — pain ${e.pain}/10` : ''}`;
  s += `## Tendon work\n\n${tendon.length ? tendon.map(line).join('\n') : '_None._'}\n\n`;
  s += `## Skill work\n\n${skill.length ? skill.map(line).join('\n') : '_None._'}\n\n`;
  s += `## Pain / discomfort\n\n${pains.length ? pains.map(e => `- ${X[e.ex].name}: ${e.pain}/10${+e.pain > cap ? ' ⚠ above cap' : ''} (${(X[e.ex].rg || []).map(r => REGIONS[r]).join(', ')})`).join('\n') : '_None logged._'}\n\n`;
  s += `## PRs\n\n${(w.prs || []).length ? w.prs.map(p => `- 🏆 **${p.name}** — ${p.text}`).join('\n') : '_None this session._'}\n\n`;
  if (w.levelUps?.length) s += `## Skill levels unlocked\n\n${w.levelUps.map(n => `- ⭐ ${n}`).join('\n')}\n\n`;
  // what to do next time, given this session (history up to and including it)
  s += `## Next session\n\n${done.map(e => { const ex = X[e.ex], h = history(db, ex.id, { before: w.date, variant: e.variant });
    return `- **${ex.name}**: ${suggest(db, ex, e.tgt, h).text}`; }).join('\n')}\n\n`;
  s += `## Notes\n\n${w.notes || ''}\n`;
  return s;
}

function exerciseMd(db, ex, paths) {
  const h = history(db, ex.id); const b = bests(ex, h);
  const best = [];
  if (ex.kind === 'load') {
    best.push(`Heaviest: ${fmtW(ex, b.maxW)} × ${b.maxWR}`);
    if (b.e1rm) best.push(`Best e1RM: ${b.e1rm}`);
    if (ex.added && b.repsAt[0]) best.push(`Max BW reps: ${b.repsAt[0]}`);
  } else if (ex.kind === 'reps' || ex.kind === 'practice') best.push(`Max reps: ${b.maxR}`);
  else if (ex.kind === 'time') best.push(`Longest: ${b.maxT}s`);
  else if (ex.kind === 'jump') best.push(`Best: ${b.maxD}${ex.dUnit || ''}`);
  else if (ex.kind === 'sprint') for (const [d, t] of Object.entries(b.sprint)) best.push(`Fastest ${d}m: ${t}s`);
  else if (ex.kind === 'carry' && b.carry) best.push(`Best: ${b.carry.w} × ${b.carry.d}m`);
  if (ex.vars) for (const v of ex.vars) { const hv = history(db, ex.id, { variant: v.id }); if (hv.length) best.push(`${v.name}: ${ex.kind === 'time' ? bests(ex, hv).maxT + 's' : bests(ex, hv).maxR + ' reps'}`); }
  const repTable = ex.kind === 'load' ? '\n### Most reps at weight\n\n| Weight | Reps |\n|---|---|\n' +
    Object.entries(b.repsAt).sort((a, c) => +c[0] - +a[0]).map(([w, r]) => `| ${fmtW(ex, +w)} | ${r} |`).join('\n') + '\n' : '';
  return yaml({ type: 'exercise', id: ex.id, category: ex.cat, kind: ex.kind, regions: (ex.rg || []).map(r => REGIONS[r]), sessions: h.length,
    best_e1rm: b.e1rm || null, last: h[0]?.date, tags: ['fitness/exercise'] }) + `${GEN}\n\n# ${ex.name}\n\nCategory: ${ex.cat}${ex.risk ? ` · ⚠ ${RISK[ex.risk]}` : ''}${ex.note ? `\n\n> ${ex.note}` : ''}\n\n` +
    `## Current best\n\n${best.map(x => `- ${x}`).join('\n')}\n${repTable}\n## History\n\n| Date | Variation | Sets | Pain | Workout |\n|---|---|---|---|---|\n` +
    h.map(e => `| ${e.date} | ${e.variant ? varName(ex, e.variant) : ''} | ${doneSets(e).map(s => fmtSet(ex, s)).join(' · ')} | ${e.pain ?? ''} | ${link(paths[e.wid])} |`).join('\n') + '\n';
}

function prMd(db, paths) {
  const rows = doneWorkouts(db).flatMap(w => (w.prs || []).map(p => ({ ...p, path: paths[w.id] })));
  return yaml({ type: 'pr-log', count: rows.length, tags: ['fitness/pr'] }) + `${GEN}\n\n# PR Log\n\n| Date | Exercise | Record | Workout |\n|---|---|---|---|\n` +
    rows.map(p => `| ${p.date} | ${cell(p.name)} | ${cell(p.text)} | ${link(p.path)} |`).join('\n') + '\n';
}

function skillsMd(db, paths) {
  const { trees, status } = db.skills, X = exMap(db);
  let s = yaml({ type: 'skills', tags: ['fitness/skills'] }) + `${GEN}\n\n# Skill Trees\n\n> ${LIMB_NOTE}\n> A level unlocks only when a logged session meets its criterion.\n\n`;
  for (const t of trees) {
    const cur = skillCurrent(t, status);
    s += `## ${t.name}\n\nCurrent: **${cur.done ? 'All complete' : cur.step.name}**\n\n`;
    for (const st of t.steps) {
      const k = status[`${t.id}/${st.id}`];
      s += `- [${k?.state === 'done' ? 'x' : ' '}] ${st.name} — _${critText(st.crit, X)}_${k?.state === 'done' ? ` (${k.date}${k.wid && paths[k.wid] ? ', ' + link(paths[k.wid]) : ''})` : k?.state === 'working' ? ' — working' : ''}${st.risk ? ` ⚠ ${RISK[st.risk]}` : ''}\n`;
    }
    s += '\n';
  }
  return s;
}

const MKEYS = ['bw', 'waist', 'chest', 'arms', 'thighs', 'hips', 'bf'];
function measurementMd(db, date) {
  const m = db.measurements.filter(x => x.date === date).at(-1), photos = (db.photos || []).filter(p => p.date === date);
  const fm = { type: 'measurement', date };
  if (m) for (const k of MKEYS) if (num(m[k]) != null) fm[k === 'bw' ? 'bodyweight' : k] = +m[k];
  fm.photos = photos.length || null; fm.tags = ['fitness/measurement'];
  let s = yaml(fm) + `\n# Measurements — ${date}\n\n`;
  if (m) s += `| Metric | Value |\n|---|---|\n` + MKEYS.filter(k => num(m[k]) != null)
    .map(k => `| ${{ bw: 'Bodyweight (lb)', bf: 'Body fat % (est.)' }[k] || k[0].toUpperCase() + k.slice(1) + ' (in)'} | ${m[k]} |`).join('\n') + '\n\n';
  if (photos.length) s += `## Photos\n\n${photos.map(p => `![[${photoPath(p).split('/').pop()}|300]]`).join(' ')}\n\n`;
  if (m?.notes) s += `## Notes\n\n${m.notes}\n`;
  return s;
}
export const photoPath = p => `${ROOT}/Measurements/Photos/${p.date} ${p.id}.jpg`;

function benchmarkMd(db, date) {
  const res = db.results.filter(r => r.date === date), defs = Object.fromEntries(db.tests.defs.map(d => [d.id, d]));
  const fm = { type: 'benchmark', date }; for (const r of res) fm[`test_${r.test}`] = +r.value; fm.tags = ['fitness/benchmark'];
  return yaml(fm) + `\n# Benchmarks — ${date}\n\n| Test | Result |\n|---|---|\n` +
    res.map(r => `| ${defs[r.test]?.name || r.test} | ${r.value} ${defs[r.test]?.unit || ''} |`).join('\n') + '\n' +
    (res.some(r => r.notes) ? `\n## Notes\n\n${res.filter(r => r.notes).map(r => `- ${defs[r.test]?.name}: ${r.notes}`).join('\n')}\n` : '');
}

function tendonMd(db, paths) {
  const X = exMap(db), cap = db.settings.painCap ?? 3;
  const rows = doneWorkouts(db).flatMap(w => w.entries.filter(e => X[e.ex]?.cat === 'tendon' && doneSets(e).length).map(e => ({ w, e, ex: X[e.ex] })));
  let s = yaml({ type: 'tendon-log', tags: ['fitness/tendon'] }) + `${GEN}\n\n# Tendon Training\n\n## Rules\n\n${TENDON_GUIDE.map(g => `- ${g}`).join('\n')}\n- Pain cap: **${cap}/10**.\n\n`;
  // weekly consistency, last 8 weeks
  s += `## Weekly consistency\n\n| Week of | Sessions with tendon work | Tendon sets | Max pain |\n|---|---|---|---|\n`;
  const today = localDate();
  for (let i = 0; i < 8; i++) {
    const to = localDate(new Date(Date.parse(today) - i * 7 * 864e5)), from = localDate(new Date(Date.parse(to) - 6 * 864e5));
    const r = rows.filter(x => x.w.date >= from && x.w.date <= to);
    const p = r.map(x => num(x.e.pain)).filter(v => v != null);
    s += `| ${from} | ${new Set(r.map(x => x.w.id)).size} | ${r.reduce((a, x) => a + doneSets(x.e).length, 0)} | ${p.length ? Math.max(...p) : ''} |\n`;
  }
  for (const [rid, rname] of Object.entries(REGIONS)) {
    const rr = rows.filter(x => x.ex.rg?.includes(rid)); if (!rr.length) continue;
    s += `\n## ${rname}\n\n| Date | Exercise | Sets | Pain during | Next day | Workout |\n|---|---|---|---|---|---|\n` +
      rr.slice(0, 20).map(({ w, e, ex }) => { const nd = nextDayPain(db, { rg: [rid] }, w.date);
        return `| ${w.date} | ${ex.name} | ${doneSets(e).map(x => fmtSet(ex, x)).join(' · ')} | ${e.pain ?? ''} | ${nd ?? ''}${nd > cap ? ' ⚠' : ''} | ${link(paths[w.id])} |`; }).join('\n') + '\n';
  }
  const ck = [...(db.checkins || [])].sort((a, b) => b.date.localeCompare(a.date)).slice(0, 30);
  s += `\n## Check-ins (next-day response + soreness)\n\n| Date | Soreness | ${Object.values(REGIONS).join(' | ')} | Notes |\n|---|---|${Object.keys(REGIONS).map(() => '---').join('|')}|---|\n` +
    ck.map(c => `| ${c.date} | ${c.soreness ?? ''} | ${Object.keys(REGIONS).map(r => c.regions?.[r] ?? '').join(' | ')} | ${cell(c.notes)} |`).join('\n') + '\n';
  return s;
}

function programMd(db) {
  const X = exMap(db); const c = db.settings.categories;
  let s = yaml({ type: 'program', tags: ['fitness/program'] }) + `${GEN}\n\n# Training Program\n\nRotation: ${db.settings.rotation.join(' → ')} — full body every other day, regardless of weekday. Off-days: pick blocks below.\n\n`;
  const table = items => `| # | Exercise | Target | Category |\n|---|---|---|---|\n` + items.map((it, i) => X[it.ex] ? `| ${i + 1} | ${X[it.ex].name} | ${fmtTarget(X[it.ex], it)} | ${X[it.ex].cat} |` : '').filter(Boolean).join('\n') + '\n\n';
  for (const t of db.program.templates) s += `## ${t.name} — ${t.title}\n\n${t.purpose || ''}\n\n` + table(t.items);
  s += `## Off-day blocks\n\n`;
  for (const b of db.program.blocks || []) s += `### ${b.name}\n\n` + table(b.items);
  s += `## Progression & rest by category\n\n| Category | Model | Increment | RPE cap | Rest (s) |\n|---|---|---|---|---|\n` +
    Object.entries(c).map(([k, v]) => `| ${v.label || k} | ${v.model} | ${v.inc ?? '—'} | ${v.rpeCap ?? '—'} | ${v.rest || 'as needed'} |`).join('\n') +
    `\n\nProgression needs: top of range on every set **and** confirmation (RPE ≤ cap or form ✓; tendon work: pain logged ≤ ${db.settings.painCap ?? 3}/10) **and** no irritated region. Form ✗ or pain above the cap holds the load; pain > 5 reduces it.\n`;
  return s;
}

// Every file the app manages. protect=true → never overwrite if edited in Obsidian.
export function buildFiles(db) {
  const files = [], paths = {};
  for (const w of doneWorkouts(db)) paths[w.id] = workoutPath(db, w);
  for (const w of doneWorkouts(db)) files.push({ path: paths[w.id], content: workoutMd(db, w), protect: true });
  const used = new Set(db.workouts.flatMap(w => w.entries.map(e => e.ex)));
  for (const ex of db.program.exercises) if (used.has(ex.id) && history(db, ex.id).length)
    files.push({ path: `${ROOT}/Exercises/${safe(ex.name)}.md`, content: exerciseMd(db, ex, paths) });
  files.push({ path: `${ROOT}/Personal Records/PR Log.md`, content: prMd(db, paths) });
  files.push({ path: `${ROOT}/Skills/Skill Trees.md`, content: skillsMd(db, paths) });
  files.push({ path: `${ROOT}/Tendon Training/Tendon Log.md`, content: tendonMd(db, paths) });
  files.push({ path: `${ROOT}/Training Program.md`, content: programMd(db) });
  for (const d of new Set([...db.measurements, ...(db.photos || [])].map(x => x.date)))
    files.push({ path: `${ROOT}/Measurements/${d}.md`, content: measurementMd(db, d), protect: true });
  for (const d of new Set(db.results.map(x => x.date)))
    files.push({ path: `${ROOT}/Benchmarks/${d}.md`, content: benchmarkMd(db, d), protect: true });
  files.push({ path: `${ROOT}/_data/tiger-backup.json`, content: JSON.stringify(db, null, 1) });
  return files;
}

// ---------- hashing / zip ----------
export function hash(s) { let h = 0x811c9dc5; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return (h >>> 0).toString(16); }
const CRC = (() => { const t = new Uint32Array(256); for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; t[n] = c; } return t; })();
const crc32 = b => { let c = ~0; for (const x of b) c = CRC[(c ^ x) & 255] ^ (c >>> 8); return ~c >>> 0; };
// Store-only zip (no compression) — enough for text, zero dependencies.
export function zip(files) {
  const enc = new TextEncoder(), parts = [], central = []; let off = 0;
  for (const f of files) {
    const name = enc.encode(f.path), data = enc.encode(f.content), crc = crc32(data);
    const h = new DataView(new ArrayBuffer(30));
    h.setUint32(0, 0x04034b50, true); h.setUint16(4, 20, true); h.setUint16(6, 0x800, true);
    h.setUint32(14, crc, true); h.setUint32(18, data.length, true); h.setUint32(22, data.length, true); h.setUint16(26, name.length, true);
    parts.push(new Uint8Array(h.buffer), name, data);
    const c = new DataView(new ArrayBuffer(46));
    c.setUint32(0, 0x02014b50, true); c.setUint16(4, 20, true); c.setUint16(6, 20, true); c.setUint16(8, 0x800, true);
    c.setUint32(16, crc, true); c.setUint32(20, data.length, true); c.setUint32(24, data.length, true); c.setUint16(28, name.length, true); c.setUint32(42, off, true);
    central.push(new Uint8Array(c.buffer), name);
    off += 30 + name.length + data.length;
  }
  const csize = central.reduce((a, b) => a + b.length, 0), e = new DataView(new ArrayBuffer(22));
  e.setUint32(0, 0x06054b50, true); e.setUint16(8, files.length, true); e.setUint16(10, files.length, true); e.setUint32(12, csize, true); e.setUint32(16, off, true);
  return new Blob([...parts, ...central, new Uint8Array(e.buffer)], { type: 'application/zip' });
}

// ---------- sync core (shared by browser + Node via an fs adapter) ----------
// io: { read(path) → string|null, write(path, content), list(dir) → names }
// extras: [{ path, blob }] binary files (photos) written once, never overwritten.
export async function syncWith(io, db, mergeFn, extras = []) {
  const report = { written: 0, same: 0, kept: [], merged: 0, backedUp: 0 };
  const day = localDate(), BK = `${ROOT}/_data/backups`;
  // 1. pull other devices' backups saved into _data/ (e.g. from the phone via Files)
  for (const n of (await io.list(`${ROOT}/_data`)).filter(n => /^tiger-backup.*\.json$/.test(n))) {
    try { const other = JSON.parse(await io.read(`${ROOT}/_data/${n}`)); const before = db.workouts.length; db = mergeFn(db, other); report.merged += db.workouts.length - before; } catch { /* ignore unreadable */ }
  }
  autoUnlock(db);
  // 2. stable note paths
  for (const w of db.workouts) if (w.status === 'done' && !w.mdPath) w.mdPath = workoutPath(db, w);
  // 3. write, protecting notes edited in Obsidian
  const stateP = `${ROOT}/_data/sync-state.json`;
  let state = {}; try { state = JSON.parse(await io.read(stateP) || '{}'); } catch { }
  // daily snapshot of the data before anything is written (kept: last 30)
  if (await io.read(`${BK}/tiger-backup-${day}.json`) == null) {
    const prev = await io.read(`${ROOT}/_data/tiger-backup.json`);
    await io.write(`${BK}/tiger-backup-${day}.json`, prev ?? JSON.stringify(db));
    if (io.remove) for (const n of (await io.list(BK)).filter(n => /^tiger-backup-\d{4}-\d\d-\d\d\.json$/.test(n)).sort().slice(0, -30)) await io.remove(`${BK}/${n}`);
  }
  for (const f of buildFiles(db)) {
    const disk = await io.read(f.path), h = hash(f.content);
    if (disk != null && hash(disk) === h) { report.same++; state[f.path] = h; continue; }
    if (f.protect && disk != null && hash(disk) !== state[f.path]) { report.kept.push(f.path); continue; }
    // a generated note edited by hand: keep a copy before overwriting
    if (disk != null && state[f.path] && hash(disk) !== state[f.path]) { await io.write(`${BK}/overwritten/${day} ${f.path.split('/').pop()}`, disk); report.backedUp++; }
    await io.write(f.path, f.content); state[f.path] = h; report.written++;
  }
  for (const x of extras) if (await io.read(x.path) == null) { await io.write(x.path, x.blob); report.written++; }
  await io.write(stateP, JSON.stringify(state, null, 1));
  db.lastSync = new Date().toISOString();
  return { db, report };
}

// Browser adapter over a FileSystemDirectoryHandle pointing at the vault root.
export function dirIO(root) {
  const dir = async (parts, create) => { let d = root; for (const p of parts) d = await d.getDirectoryHandle(p, { create }); return d; };
  return {
    async read(path) { const p = path.split('/'); try { const d = await dir(p.slice(0, -1), false); return await (await (await d.getFileHandle(p.at(-1))).getFile()).text(); } catch { return null; } },
    async write(path, content) { const p = path.split('/'); const d = await dir(p.slice(0, -1), true); const w = await (await d.getFileHandle(p.at(-1), { create: true })).createWritable(); await w.write(content); await w.close(); },
    async remove(path) { const p = path.split('/'); try { const d = await dir(p.slice(0, -1), false); await d.removeEntry(p.at(-1)); } catch { } },
    async list(path) { try { const d = await dir(path.split('/'), false); const out = []; for await (const k of d.keys()) out.push(k); return out; } catch { return []; } },
  };
}
